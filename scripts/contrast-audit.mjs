#!/usr/bin/env node
/**
 * WCAG contrast audit for the Scene 3 environments. Colours are read from src/theme/tokens.ts (single source),
 * alpha is composited over the real room ground: color-mix(hue 10%, ink-950), plus a worst-case ground where
 * the backdrop glow adds up to 30% hue. Writes a markdown report.
 *
 * Usage: node scripts/contrast-audit.mjs [out.md]
 */
import fs from 'node:fs';

const src = fs.readFileSync('src/theme/tokens.ts', 'utf8');
const tok = (name) => src.match(new RegExp(`${name}:\\s*'(#[0-9A-Fa-f]{6})'`))[1];
const C = { ink950: tok('ink950'), ink900: tok('ink900'), ivory: tok('ivory'), silver: tok('silver'), champagne: tok('champagne'), cyan: tok('cyan') };
const hues = {};
for (const m of src.matchAll(/(\w+):\s*\{\s*night:\s*'(#[0-9A-Fa-f]{6})'/g)) hues[m[1]] = m[2];

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const mix = (a, b, t) => a.map((v, i) => v * (1 - t) + b[i] * t); // t of b over a
const lum = (c) => {
  const [r, g, b] = c.map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// [label, colour token, alpha, kind]. kind: normal (4.5) | large (3) | ui (3) | decor (informational only)
const fgs = [
  ['Heading (ivory, large serif)', 'ivory', 1, 'large'],
  ['Blurb (ivory, 17px)', 'ivory', 1, 'normal'],
  ['Involves paragraph (ivory/75, 14px)', 'ivory', 0.75, 'normal'],
  ['Discipline chip text (ivory/80, 10px mono)', 'ivory', 0.8, 'normal'],
  ['Detail list items (ivory/85, 14px)', 'ivory', 0.85, 'normal'],
  ['Eyebrow label (champagne, 11px mono)', 'champagne', 1, 'normal'],
  ['Eyebrow counter (silver, 11px mono)', 'silver', 1, 'normal'],
  ['List title (champagne, 10px mono)', 'champagne', 1, 'normal'],
  ['Disclaimer (silver, 10px mono)', 'silver', 1, 'normal'],
  ['"Explore Careers" label (ivory/90)', 'ivory', 0.9, 'normal'],
  ['"Soon" tag (silver)', 'silver', 1, 'normal'],
  ['Eyebrow separator dash (silver/60, decorative)', 'silver', 0.6, 'decor'],
  ['Chip border (ivory/20)', 'ivory', 0.2, 'ui'],
  ['Disabled button border (ivory/30)', 'ivory', 0.3, 'decor'],
  ['Focus ring (cyan)', 'cyan', 1, 'ui'],
  ['Figure labels in artwork (ivory 0.55–0.95, 10–12px mono, aria-hidden)', 'ivory', 0.55, 'decor'],
  ['Figure labels in artwork (ivory 0.72 default)', 'ivory', 0.72, 'decor'],
];

const rows = [];
let fails = 0;
for (const [domain, hue] of Object.entries(hues)) {
  const grounds = {
    base: mix(rgb(C.ink950), rgb(hue), 0.1),
    glow: mix(rgb(C.ink950), rgb(hue), 0.3),
  };
  for (const [gName, bg] of Object.entries(grounds)) {
    for (const [label, token, alpha, kind] of fgs) {
      const fg = mix(bg, rgb(C[token]), alpha);
      const r = ratio(fg, bg);
      const need = kind === 'normal' ? 4.5 : 3;
      const pass = kind === 'decor' ? null : r >= need;
      if (pass === false) fails++;
      rows.push({ domain, ground: gName, label, kind, r, need, pass });
    }
    // hue as graphical element (bullet dots, rules, art strokes) against its ground
    const r = ratio(rgb(hue), bg);
    rows.push({ domain, ground: gName, label: 'Domain hue (bullets, name rule, artwork strokes)', kind: 'ui', r, need: 3, pass: r >= 3 });
    if (r < 3) fails++;
  }
}

const f = (n) => n.toFixed(2);
let md = `# Scene 3 contrast audit\n\nGenerated by \`scripts/contrast-audit.mjs\` from \`src/theme/tokens.ts\`. Ground = color-mix(hue 10%, ink-950) ("base"); "glow" = worst case where backdrop glow adds up to 30% hue.\nThresholds: normal text 4.5:1, large text / UI / graphics 3:1. "decor" = decorative or aria-hidden (informational only).\n\n`;
const byLabel = {};
for (const r of rows) (byLabel[r.label] ||= []).push(r);
md += '| Element | Kind | Min ratio (base) | Min ratio (glow) | Required | Result |\n|---|---|---:|---:|---:|---|\n';
for (const [label, rs] of Object.entries(byLabel)) {
  const min = (g) => Math.min(...rs.filter((r) => r.ground === g).map((r) => r.r));
  const k = rs[0].kind;
  const bad = rs.filter((r) => r.pass === false);
  md += `| ${label} | ${k} | ${f(min('base'))} | ${f(min('glow'))} | ${k === 'normal' ? '4.5' : '3.0'} | ${k === 'decor' ? 'info' : bad.length ? `FAIL (${[...new Set(bad.map((b) => b.domain))].join(', ')})` : 'pass'} |\n`;
}
md += `\nFailures: ${fails}\n`;
const out = process.argv[2] || 'docs/qa-screenshots/explore/contrast-report.md';
fs.writeFileSync(out, md);
console.log(md);
